export function detectTech(html, headerText) {
    const out = [];
    for (const s of SIGNATURES) {
        if ((s.h && s.h.test(html)) || (s.hd && s.hd.test(headerText))) out.push({ name: s.n, category: s.c });
    }
    return out;
}
