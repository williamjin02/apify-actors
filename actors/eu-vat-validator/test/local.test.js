import assert from 'node:assert/strict';
import { parseVat, nameMatch, normName, cleanField } from '../src/vat.js';
let pass = 0; let fail = 0;
const t = (n, fn) => { try { fn(); pass++; console.log(`ok   ${n}`); } catch (e) { fail++; console.log(`FAIL ${n}\n     ${e.message}`); } };
t('parse: plain', () => assert.deepEqual(parseVat('IE6388047V'), { country: 'IE', number: '6388047V', vatId: 'IE6388047V' }));
t('parse: spaces/dots/lowercase', () => assert.equal(parseVat('de 811.128.135').vatId, 'DE811128135'));
t('parse: GR -> EL', () => assert.equal(parseVat('GR094259216').vatId, 'EL094259216'));
t('parse: prefix words', () => assert.equal(parseVat('VAT No: FR40303265045').vatId, 'FR40303265045'));
t('parse: Austria U', () => assert.equal(parseVat('ATU14000905').vatId, 'ATU14000905'));
t('parse: NL B', () => assert.equal(parseVat('nl004495445b01').vatId, 'NL004495445B01'));
t('parse: XI Northern Ireland', () => assert.equal(parseVat('XI 123456789').vatId, 'XI123456789'));
t('parse: GB unsupported', () => assert.equal(parseVat('GB123456789').status, 'unsupported_country'));
t('parse: CHE unsupported', () => assert.equal(parseVat('CHE-123.456.789').status, 'unsupported_country'));
t('parse: unknown code', () => assert.equal(parseVat('XX123456789').status, 'invalid_format'));
t('parse: wrong length', () => assert.equal(parseVat('DE12').status, 'invalid_format'));
t('parse: missing prefix', () => assert.equal(parseVat('6388047V').status, 'invalid_format'));
t('parse: defaultCountry', () => assert.equal(parseVat('6388047V', 'IE').vatId, 'IE6388047V'));
t('parse: FR letters with defaultCountry', () => assert.equal(parseVat('AB123456789', 'FR').vatId, 'FRAB123456789'));
t('parse: empty', () => assert.equal(parseVat('').status, 'invalid_input'));
t('normName strips legal forms', () => assert.equal(normName('Google Ireland Limited'), 'google ireland'));
t('nameMatch', () => {
    assert.equal(nameMatch('Google Ireland Ltd', 'GOOGLE IRELAND LIMITED'), 'exact');
    assert.equal(nameMatch('Google', 'GOOGLE IRELAND LIMITED'), 'close');
    assert.equal(nameMatch('Google Cloud EMEA', 'GOOGLE IRELAND LIMITED'), 'partial');
    assert.equal(nameMatch('Apple', 'GOOGLE IRELAND LIMITED'), 'mismatch');
    assert.equal(nameMatch('SAP', '---'), 'not_available');
    assert.equal(nameMatch(null, 'X'), null);
    assert.equal(nameMatch('Müller GmbH', 'MULLER'), 'exact');
});
t('cleanField', () => { assert.equal(cleanField('---'), null); assert.equal(cleanField(' A '), 'A'); });
console.log(`\n${pass} passed, ${fail} failed`); if (fail) process.exit(1);
